  TK.ROLES_RACI = { R: 'Responsable', A: 'Dueño (Accountable)', C: 'Consultado', I: 'Informado' };

  TK.actividadLibre = function (actividad) { return TK.UBICACION_LIBRE.indexOf(actividad) >= 0; };
  TK.raciDe = function (actividad) { return Object.keys(TK.RACI[actividad] || {}).reduce(function (m, u) { m[u + TK.DOMINIO] = TK.RACI[actividad][u]; return m; }, {}); };
  // Lista [{correo, codigo}] ordenada: R, A, C, I.
  TK.participantesRaci = function (actividad) {
    var r = TK.raciDe(actividad), orden = { R: 0, A: 1, C: 2, I: 3 };
    function peso(c) { return Math.min.apply(null, c.split('/').map(function (x) { return orden[x]; })); }
    return Object.keys(r).map(function (k) { return { correo: k, codigo: r[k] }; }).sort(function (a, b) { return peso(a.codigo) - peso(b.codigo); });
  };
  // Participa de forma activa (R, A o C): por eso ve el ticket. El rol I solo recibe aviso.
  TK.tieneRolActivo = function (raci, correo) { return !!raci && /[RAC]/.test(raci[correo] || ''); };

  // Responsable por defecto: quien tiene R puro; si no, R/C y luego R/I. Sin RACI, cae a la coordinación.
  TK.responsablePorDefecto = function (categoria, actividad) {
    var p = TK.participantesRaci(actividad || '');
    var pref = ['R', 'R/C', 'R/I'];
    for (var i = 0; i < pref.length; i++) {
      var h = p.filter(function (x) { return x.codigo === pref[i] && TK.usuario(x.correo); })[0];
      if (h) return h.correo;
    }
    var cand = TK.USUARIOS.filter(function (u) { return u.rol === 'Coordinador'; });
    return cand.length ? cand[0].correo : null;
  };
